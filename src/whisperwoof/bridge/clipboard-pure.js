/**
 * Clipboard formats that say "don't remember this copy". macOS: the
 * nspasteboard.org markers (1Password, Bitwarden, KeePassXC, Apple
 * Passwords…) and older app-specific ones. Windows: the formats KeePass,
 * Bitwarden and 1Password set to stay out of Clipboard History. Linux:
 * KDE's password-manager hint (KeePassXC).
 */
const PRIVATE_CLIPBOARD_FORMATS = Object.freeze({
  darwin: Object.freeze([
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "net.antelle.keeweb",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
  ]),
  win32: Object.freeze(["ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore"]),
  linux: Object.freeze(["x-kde-passwordManagerHint"]),
});

/** Windows formats holding a DWORD; 0 means "keep out of history / the cloud". */
const WIN32_ZERO_MEANS_PRIVATE = Object.freeze(["CanIncludeInClipboardHistory", "CanUploadToCloudClipboard"]);

/**
 * Whether the current copy asks not to be remembered. `has(format)` and
 * `readBuffer(format)` are Electron's clipboard functions. When the check
 * itself fails the copy counts as private: missing one copy is the safe
 * mistake, keeping a password is not.
 */
function isPrivateClipboard({ platform, has, readBuffer }) {
  if (typeof has !== "function") return false;
  try {
    for (const format of PRIVATE_CLIPBOARD_FORMATS[platform] || []) {
      if (has(format)) return true;
    }
    if (platform === "win32") {
      for (const format of WIN32_ZERO_MEANS_PRIVATE) {
        if (!has(format)) continue;
        const value = typeof readBuffer === "function" ? readBuffer(format) : null;
        if (!value || value.length < 4 || value.readUInt32LE(0) === 0) return true;
      }
    }
    return false;
  } catch {
    return true;
  }
}

